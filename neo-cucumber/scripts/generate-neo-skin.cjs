const fs = require("fs");
// Run from the repo root: node neo-cucumber/scripts/generate-neo-skin.cjs
//
// Pulls the stylesheet rules NEO builds at runtime, by running its own
// initSkin against its own defaults. Transcribing them by hand is how the
// toolbox ended up lavender with the wrong bevels.
const src = fs.readFileSync("neo/src/container.js", "utf8");

function extract(name) {
  const start = src.indexOf("Neo." + name + " = function");
  if (start < 0) throw new Error("missing " + name);
  let i = src.indexOf("{", start), depth = 0;
  for (let j = i; j < src.length; j++) {
    if (src[j] === "{") depth++;
    else if (src[j] === "}") { depth--; if (depth === 0) return src.slice(start, j + 1); }
  }
  throw new Error("unbalanced " + name);
}

const rules = [];
const Neo = {
  config: {
    color_icon: "#ccccff", color_iconselect: "#ffaaaa", color_text: "#666699",
    color_bar: "#6f6fae", color_bk: "#ffffff", color_frame: "#666699",
    tool_color_button: "#e8dfae", tool_color_button2: "#f8daaa",
    tool_color_text: "#773333", tool_color_bar: "#ddddff",
    tool_color_frame: "#000000", color_bar_select: "#407675",
  },
  painter: null,
  getStyleSheet: () => ({}),
  addRule: (sel, prop, val) => {
    if (val !== undefined && val !== null) rules.push([sel, prop, val]);
  },
  backgroundImage: () => "",
  // Positions the column; emits no rules, so a stub is enough
  setToolSide: () => {},
  toolSide: 0,
};
eval(extract("multColor"));
eval(extract("initSkin"));
Neo.initSkin();

const bySel = new Map();
for (const [sel, prop, val] of rules) {
  if (prop === "background-image" && String(val).includes("url()")) continue;
  if (!bySel.has(sel)) bySel.set(sel, []);
  bySel.get(sel).push("  " + prop + ": " + val + ";");
}
let out = `/*
 * The rules container.js injects at runtime through Neo.addRule.
 *
 * They are not in neo.css because NEO computes them from its colour config,
 * including the bevels it derives by multiplying color_icon and color_bar by
 * 1.3 and 0.7. Generated by running NEO's own initSkin with its own defaults,
 * so the numbers are its numbers rather than my reading of them.
 *
 * Generated. Do not hand-edit -- re-run the generator instead.
 */

`;
for (const [sel, decls] of bySel) out += sel + " {\n" + decls.join("\n") + "\n}\n\n";
fs.writeFileSync("neo-cucumber/src/styles/neoSkin.css", out);
console.log("rules:", rules.length, "selectors:", bySel.size);
